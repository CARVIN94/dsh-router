/**
 * 分类的默认开关状态。
 *
 * ⚠️ **已保存的配置优先**：用户在面板改过的分类以 `extStore` 里的为准，
 * 这里只在「用户从没碰过这一类」时提供默认值。所以**改 `defaultOn` 不会
 * 覆盖用户已有选择**（这是刻意的 —— 否则改默认值等于静默改用户配置）。
 */
export function defaultToggles(): Record<string, boolean> {
  const out: Record<string, boolean> = {}
  for (const c of PROMPT_CATEGORIES) out[c.id] = c.defaultOn
  return out
}
