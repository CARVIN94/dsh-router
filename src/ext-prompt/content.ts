/** 一个可独立开关的提示词分类。 */
export interface PromptCategory {
  /** 稳定 id：面板开关与 `router.extStore` 数据块的键，**改名会丢用户配置**。 */
  readonly id: string
  /** 面板显示名。 */
  readonly title: string
  /**
   * 是否默认开启。
   *
   * 默认**关**的只有「可以按项目关掉」的那几条（领地/结构/交付/执行）；
   * 身份、底线、收口这类是准则的骨架，一律默认开 —— 默认关掉等于静默移除规则。
   */
  readonly defaultOn: boolean
  /** 段落正文（逐字）。空串 = 该分类不产出任何 prompt 文本。 */
  readonly body: string
}

